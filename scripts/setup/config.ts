import { validHandle } from "../../packages/core/src/params.ts";
import { parseJsonc } from "./jsonc.ts";

/** One DNS label: lowercase letters, digits and inner hyphens. */
const LABEL = /^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/;

/**
 * Check a `--domain` value as a bare hostname. Returns an error message, or
 * undefined when it is acceptable. No scheme, path, port, wildcard or address;
 * at least two labels.
 */
export function domainError(domain: string): string | undefined {
  if (domain.length > 200) return "domain is too long";
  const labels = domain.split(".");
  if (labels.length < 2) return `domain must have at least two parts, like example.com: ${show(domain)}`;
  if (!labels.every((l) => LABEL.test(l))) {
    return `domain must be a bare hostname of lowercase letters, digits, hyphens and dots (no scheme, path, port or wildcard): ${show(domain)}`;
  }
  if (/^[0-9]+$/.test(labels[labels.length - 1] as string)) {
    return `domain must end in a name, not a number: ${show(domain)}`;
  }
  return undefined;
}

function show(value: string): string {
  return JSON.stringify(value.length > 60 ? `${value.slice(0, 60)}...` : value);
}

/** The board's own handle rule (`validHandle` in core), with a message. */
export function handleError(handle: string): string | undefined {
  return validHandle(handle)
    ? undefined
    : "handle must be 1-32 letters, digits, '-' or '_', starting with a letter or digit, and not a reserved word";
}

export interface Hosts {
  web: string;
  api: string;
}

export function domainHosts(domain: string): Hosts {
  return { web: `https://app.${domain}`, api: `https://api.${domain}` };
}

const GENERATED_HEADER = [
  "// SPDX-FileCopyrightText: 2026 Curtis Galloway",
  "// SPDX-License-Identifier: Apache-2.0",
  "//",
  "// Generated by `npm run setup` from wrangler.jsonc; gitignored. Edit wrangler.jsonc",
  "// or rerun setup, not this file.",
].join("\n");

/**
 * The deploy config: the checked-in config plus the hostnames and the build id.
 * With a domain, two Custom Domains and no workers.dev address; without one, no
 * routes and the account's workers.dev address. Preview URLs stay off in both.
 * `buildId` becomes the plain var `BBS_BUILD_ID`, which `/health` reports so
 * setup can tell the version it just deployed from the one still answering.
 * `commit` becomes the plain var `BBS_GIT_COMMIT`, which `bbs_whoami` and
 * `/health` report; setup omits it when the checkout's commit is unknown.
 * `approval` becomes the plain vars `BBS_REQUIRE_APPROVAL` and
 * `BBS_APPROVER_ALLOW_SYNCED` (each `"1"`): the board then requires a passkey's
 * approval for the gated human-only actions (design §12). With neither flag the
 * vars are left out, so a redeploy without the flag turns approval off.
 */
export function generateConfig(
  checkedIn: string,
  domain: string | undefined,
  buildId?: string,
  commit?: string,
  approval: { required?: boolean | undefined; allowSynced?: boolean | undefined } = {},
): Record<string, unknown> {
  const base = parseJsonc(checkedIn);
  const extra: Record<string, string> = {
    ...(buildId === undefined ? {} : { BBS_BUILD_ID: buildId }),
    ...(commit === undefined ? {} : { BBS_GIT_COMMIT: commit }),
    ...(approval.required ? { BBS_REQUIRE_APPROVAL: "1" } : {}),
    ...(approval.required && approval.allowSynced ? { BBS_APPROVER_ALLOW_SYNCED: "1" } : {}),
  };
  const withBuild: Record<string, unknown> =
    Object.keys(extra).length === 0 ? base : { ...base, vars: { ...(base.vars as Record<string, unknown> | undefined), ...extra } };
  if (domain === undefined) return { ...withBuild, workers_dev: true, preview_urls: false };
  return {
    ...withBuild,
    routes: [
      { pattern: `app.${domain}`, custom_domain: true },
      { pattern: `api.${domain}`, custom_domain: true },
    ],
    workers_dev: false,
    preview_urls: false,
  };
}

export function renderConfig(config: Record<string, unknown>): string {
  return `${GENERATED_HEADER}\n${JSON.stringify(config, null, 2)}\n`;
}
